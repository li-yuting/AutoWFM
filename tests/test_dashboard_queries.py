def test_inc_d():
    # 方案D：H点 = end[H]-start[H]，start=first[H]，end=first[H+1]或latest[H](当前小时)
    first = {9: 40, 10: 100, 11: 130}
    # 已完成小时(9,10)=first[H+1]-first[H]；当前小时(11)=latest[11]-first[11]
    assert Q._inc_d(first, {9: 40, 10: 100, 11: 130}, [9, 10, 11]) == {9: 60, 10: 30, 11: 0}   # 11整点刚采完
    assert Q._inc_d(first, {9: 40, 10: 100, 11: 160}, [9, 10, 11]) == {9: 60, 10: 30, 11: 30}  # 11实时进度
    # 当前小时整点刚采完(只有首条 first=latest) -> 0
    assert Q._inc_d({9: 40}, {9: 40}, [9]) == {9: 0}
    # 缺口小时(无首条) -> None
    assert Q._inc_d({9: 40, 11: 130}, {9: 40, 11: 130}, [9, 10, 11])[10] is None

